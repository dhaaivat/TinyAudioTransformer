seg = held_out[[len(held_out) // 2]]

waves = {"clean": clip, **{f"{snr} dB": mix_at_snr(clip, seg, float(snr)) for snr in (20, 10, 5, 0)}}
fig, axes = plt.subplots(1, len(waves), figsize=(3.6 * len(waves), 3.2), sharey=True)
for ax, (title, w) in zip(axes, waves.items()):
    ax.imshow(fbank(w, 128, 128)[0].T, origin="lower", aspect="auto", cmap="magma")
    ax.set_title(f"'{WORD}' {title}", fontsize=9)
    ax.set_xlabel("frame (10 ms)")
axes[0].set_ylabel("mel bin")
plt.tight_layout()
plt.show()
for title, w in waves.items():
    print(title)
